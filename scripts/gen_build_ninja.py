"""
gen_build_ninja.py - erzeugt build/build.ninja fuer den Vollbau der gelifteten TUs.

Vorteile gegenueber der sequenziellen cmd-Schleife:
  * parallele Kompilierung (ninja -j<N>, Default = Kernzahl+2)
  * inkrementell (nur geaenderte TUs + Link)
  * ccache als Compiler-Praefix, falls vorhanden (schnelle Rebuilds)

Aufruf (aus dem Repo-Root):
    python scripts/gen_build_ninja.py

Danach:
    Vollbau:        ninja -f build/build.ninja
    inkrementell:   ninja -f build/build.ninja      (nach Aenderung an juiced_lifted/*.c)
    nur ein Objekt: ninja -f build/build.ninja build/full/recomp_0000.o

Voraussetzung: build/full/link_stubs.c existiert (scripts/build_full.cmd erzeugt sie).
"""
import glob
import os
import sys

ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else ".")
GCC = "C:/msys64/mingw32/bin/gcc.exe"
CCACHE = "C:/msys64/mingw32/bin/ccache.exe"

GEN_DIR = "juiced_lifted"
INC_H = "juiced_lifted/recomp_funcs.h"
INC_TYPES = "pcrecomp/runtime/recomp32/recomp_types.h"

CFLAGS = ("-c -O0 -w -ffunction-sections -fdata-sections "
          "-Wno-error=implicit-function-declaration "
          "--param ggc-min-heapsize=32768 --param ggc-min-expand=10")
INC = "-I pcrecomp/runtime/recomp32"
DEFS = "-include juiced_lifted/recomp_funcs.h"


def main():
    use_ccache = os.path.exists(CCACHE)
    cc = f"{CCACHE} {GCC}" if use_ccache else GCC

    tus = sorted(os.path.basename(p)
                 for p in glob.glob(os.path.join(ROOT, GEN_DIR, "recomp_[0-9]*.c")))
    if not tus:
        raise SystemExit("keine recomp_[0-9]*.c unter %s gefunden" % GEN_DIR)

    objs = []
    lines = []
    lines.append("ninja_required_version = 1.5\n")
    lines.append("# Ninja-Zustand (.ninja_log/.ninja_deps) unter build\\ ablegen\n")
    lines.append("builddir = build\n")
    lines.append(f"# auto-generated by scripts/gen_build_ninja.py (ccache={use_ccache})\n")
    lines.append(f"cc = {cc}\n")
    lines.append(f"gcc = {GCC}\n")
    lines.append(f"cflags = {CFLAGS}\n")
    lines.append(f"inc = {INC}\n")
    lines.append(f"defs = {DEFS}\n")
    lines.append("rule cc\n")
    lines.append("  command = $cc $cflags $inc $defs $in -o $out\n")
    lines.append("  description = CC $out\n")
    lines.append("rule link\n")
    lines.append("  command = $gcc $in -Wl,--gc-sections -o $out\n")
    lines.append("  description = LINK $out\n")
    lines.append("rule linkrun\n")
    lines.append("  command = $gcc $in -Wl,--gc-sections -Wl,--image-base,0x10000000 -o $out\n")
    lines.append("  description = LINKRUN $out\n")
    lines.append("rule stubs\n")
    lines.append("  command = python scripts/gen_link_stubs.py build/full $out "
                 "C:/msys64/mingw32/bin/nm.exe logs/link_stubs.txt\n")
    lines.append("  description = STUBS $out\n\n")

    for tu in tus:
        o = "build/full/%s.o" % tu[:-2]
        objs.append(o)
        lines.append(f"build {o}: cc {GEN_DIR}/{tu} | {INC_H} {INC_TYPES}\n")

    lines.append(f"build build/full/poc_main.o: cc poc/main.c | {INC_TYPES}\n")
    lines.append(f"build build/full/runtime_main.o: cc poc/runtime_main.c | {INC_TYPES} pcrecomp/runtime/recomp32/image_loader.h\n")
    lines.append("build build/full/image_loader.o: cc pcrecomp/runtime/recomp32/image_loader.c | pcrecomp/runtime/recomp32/image_loader.h\n")
    lines.append(f"build build/full/recomp_dispatch.o: cc {GEN_DIR}/recomp_dispatch.c | {INC_H} {INC_TYPES}\n")
    stub_inputs = " ".join(["build/full/poc_main.o", "build/full/recomp_dispatch.o"] + objs)
    lines.append(f"\nbuild build/full/link_stubs.c: stubs {stub_inputs}\n")
    lines.append("build build/full/link_stubs.o: cc build/full/link_stubs.c\n")

    link_inputs = " ".join(["build/full/poc_main.o", "build/full/link_stubs.o"] + objs)
    lines.append(f"\nbuild build/juiced_full.exe: link {link_inputs}\n")
    run_inputs = " ".join(["build/full/runtime_main.o", "build/full/image_loader.o",
                           "build/full/recomp_dispatch.o",
                           "build/full/link_stubs.o"] + objs)
    lines.append(f"build build/juiced_run.exe: linkrun {run_inputs}\n")
    lines.append("\ndefault build/juiced_full.exe build/juiced_run.exe\n")

    out_path = os.path.join(ROOT, "build", "build.ninja")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(lines))

    print("build.ninja geschrieben: %s" % out_path)
    print("  TUs: %d, ccache: %s" % (len(tus), use_ccache))


if __name__ == "__main__":
    main()
